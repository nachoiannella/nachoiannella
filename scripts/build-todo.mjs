// Generates CONTENT_TODO.md from every [COMPLETAR] placeholder in the source.
// Syntax:  TS strings  {{todo:id|text}}  /  {{todo!:id|text}}  (! = possibly NDA)
//          MDX         <Todo id="id">text</Todo>  /  <Todo id="id" nda>text</Todo>
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const files = ['content', 'lib', 'components', 'app'].flatMap((d) => walk(join(root, d))).filter((f) => /\.(ts|tsx|mdx)$/.test(f));

const items = new Map();
const add = (id, text, nda, file, line) => {
  const lang = /\.es\.mdx$/.test(file) ? 'es' : /\.en\.mdx$/.test(file) ? 'en' : null;
  const it = items.get(id) || { id, nda: false, texts: new Set(), where: new Set() };
  it.nda ||= nda;
  if (lang !== 'es') it.texts.add(text.trim());
  else if (!it.texts.size) it.texts.add(text.trim());
  it.where.add(`${relative(root, file)}:${line}`);
  items.set(id, it);
};
for (const f of files) {
  const lines = readFileSync(f, 'utf8').split('\n');
  lines.forEach((l, i) => {
    for (const m of l.matchAll(/\{\{todo(!?):([^|]+)\|([^}]+)\}\}/g)) add(m[2], m[3], m[1] === '!', f, i + 1);
    for (const m of l.matchAll(/<Todo id="([^"]+)"( nda)?>([^<]+)<\/Todo>/g)) add(m[1], m[3], !!m[2], f, i + 1);
  });
}

const area = (it) => {
  const w = [...it.where].join(' ');
  if (w.includes('despegar-cart') || it.id.startsWith('cart')) return 'Case study — Despegar Cart & Cross-sell';
  if (w.includes('sofia') || it.id.startsWith('sofia')) return 'Case study — SOFIA';
  if (w.includes('travel-mode') || it.id.startsWith('tm-')) return 'Case study — Travel Mode';
  if (it.id.startsWith('testimonial')) return 'Testimonials';
  if (it.id.startsWith('ritual') || it.id.startsWith('lead') || it.id.startsWith('team')) return 'How I lead';
  if (/v0|agents/.test(it.id)) return 'Design + AI';
  return 'Home / profile';
};
const groups = {};
for (const it of items.values()) (groups[area(it)] ||= []).push(it);

const list = [...items.values()];
const nda = list.filter((i) => i.nda);
let md = `# CONTENT_TODO — what Nacho needs to fill in

${list.length === 0 ? '✅ **Nothing pending.** There are no `[COMPLETAR]` placeholders left in the site.\n' : ''}

_Generated by \`npm run todo\` (also runs on every build) from the source. Do not edit the list by hand — edit the placeholder in the file shown and re-run._

**${list.length} unique placeholders** (each appears in both EN and ES versions) · **${nda.length} flagged as possibly under NDA**.

Every placeholder renders on the live site as a yellow \`[COMPLETAR: …]\` tag, so nothing can silently ship unfilled. To resolve one, replace the \`{{todo:…}}\` / \`<Todo>\` markup with real text **in both languages**.

`;
for (const [g, its] of Object.entries(groups)) {
  md += `\n## ${g}\n\n| # | id | What’s missing | NDA? | Where |\n|---|---|---|---|---|\n`;
  its.forEach((it, n) => {
    md += `| ${n + 1} | \`${it.id}\` | ${[...it.texts][0].replace(/\|/g, '/')} | ${it.nda ? '⚠️ yes' : ''} | ${[...it.where].map((w) => `\`${w}\``).join('<br>')} |\n`;
  });
}
if (nda.length) {
  md += `\n## ⚠️ Possibly-NDA numbers (check with Despegar / Mercado Libre before publishing)\n\n`;
  for (const it of nda) md += `- \`${it.id}\` — ${[...it.texts][0]}\n`;
}
md += '\n' + readFileSync(join(root, 'content/TODO_NOTES.md'), 'utf8');
writeFileSync(join(root, 'CONTENT_TODO.md'), md);
console.log(`todo: ${list.length} placeholders (${nda.length} NDA-flagged) -> CONTENT_TODO.md`);
